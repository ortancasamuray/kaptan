#!/usr/bin/env python3
"""Regenerate the translation catalogs.

Collects @tr("...") strings from ui/, tr("...")/trf("...") from src/, plus tools/extra_msgids.json
(strings that reach tr() indirectly), then for every language in LANGUAGES writes
lang/<code>/LC_MESSAGES/kaptan.po from tools/translations/<code>.json and src/i18n_languages.rs.

Turkish must be complete (the run fails otherwise); other languages fall back to English for
missing strings and are reported. Placeholders ({}) must match in every language.

Translations: Stacer's catalogs (by its translators) where Stacer had the same text; the rest
were translated for Kaptan and have not been reviewed by native speakers yet.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TRANSLATIONS = ROOT / "tools/translations"

# (code, native name) — code is the folder name under lang/ and the value stored in settings
LANGUAGES = [
    ("ar", "العربية"), ("ca", "Català"), ("cs", "Čeština"), ("de", "Deutsch"), ("es", "Español"),
    ("eu", "Euskara"), ("fr", "Français"), ("gl", "Galego"), ("hi", "हिन्दी"), ("hu", "Magyar"),
    ("it", "Italiano"), ("kn", "ಕನ್ನಡ"), ("ko", "한국어"), ("ml", "മലയാളം"), ("nl", "Nederlands"),
    ("oc", "Occitan"), ("pl", "Polski"), ("pt", "Português"), ("ro", "Română"), ("ru", "Русский"),
    ("sv", "Svenska"), ("tr", "Türkçe"), ("uk", "Українська"), ("vi", "Tiếng Việt"),
    ("zh_CN", "简体中文"), ("zh_TW", "正體中文"),
]
REQUIRED_COMPLETE = {"tr"}


def collect():
    lit = r'"((?:[^"\\]|\\.)*)"'
    ids = set()
    for f in (ROOT / "ui").rglob("*.slint"):
        ids |= set(re.findall(r"@tr\(" + lit, f.read_text()))
    for f in (ROOT / "src").rglob("*.rs"):
        ids |= set(re.findall(r"\btrf?\(" + lit, f.read_text()))
    ids = {i.replace('\\"', '"') for i in ids}
    ids |= set(json.loads((ROOT / "tools/extra_msgids.json").read_text()))
    return sorted(ids, key=str.lower)


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_po(code, ids, tr):
    out = ['msgid ""', 'msgstr ""', '"Project-Id-Version: kaptan\\n"', f'"Language: {code}\\n"',
           '"MIME-Version: 1.0\\n"', '"Content-Type: text/plain; charset=UTF-8\\n"',
           '"Content-Transfer-Encoding: 8bit\\n"', ""]
    for i in ids:
        out += [f'msgid "{esc(i)}"', f'msgstr "{esc(tr.get(i, ""))}"', ""]
    path = ROOT / f"lang/{code}/LC_MESSAGES/kaptan.po"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))


def write_rust():
    lines = ["// Generated by tools/i18n.py — do not edit.", "",
             "/// (code, native name, gettext catalog) of the bundled languages besides English.",
             "pub const LANGUAGES: &[(&str, &str, &str)] = &["]
    for code, name in LANGUAGES:
        lines.append(f'    ("{code}", "{name}", include_str!("../lang/{code}/LC_MESSAGES/kaptan.po")),')
    lines += ["];", ""]
    (ROOT / "src/i18n_languages.rs").write_text("\n".join(lines))


def main():
    ids = collect()
    errors, report = [], []
    for code, name in LANGUAGES:
        path = TRANSLATIONS / f"{code}.json"
        tr = json.loads(path.read_text()) if path.exists() else {}
        missing = [i for i in ids if not tr.get(i)]
        for i in ids:
            t = tr.get(i)
            if t and t.count("{}") != i.count("{}"):
                errors.append(f"{code}: placeholder mismatch: {i!r} -> {t!r}")
        if code in REQUIRED_COMPLETE and missing:
            errors.append(f"{code}: missing translations:\n  " + "\n  ".join(missing))
        unused = sorted(set(tr) - set(ids))
        report.append(f"{code:6} {len(ids) - len(missing):4}/{len(ids)}"
                      + (f"  missing {len(missing)} (English fallback)" if missing else "")
                      + (f"  unused {len(unused)}" if unused else ""))
        write_po(code, ids, tr)
    write_rust()
    print(f"{len(ids)} strings\n" + "\n".join(report))
    if errors:
        sys.exit("\n".join(errors))


main()
