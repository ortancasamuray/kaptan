#!/usr/bin/env python3
"""Build an Arch Linux package (.pkg.tar.zst) from an already compiled tree, without makepkg.

Usage: mkpkg.py <source-tree> <out-dir>
Reads pkgname/pkgver/pkgrel/pkgdesc/url/license/depends/optdepends from the PKGBUILD next to this
script, lays out the same files as its package() function, and writes .PKGINFO, .BUILDINFO-less
.MTREE and the payload as a root-owned tar compressed with the zstd command.
"""
import gzip, hashlib, io, os, re, shlex, subprocess, sys, tarfile, time

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [  # (source, destination, mode) - keep in sync with PKGBUILD package()
    ("target/release/kaptan", "usr/bin/kaptan", 0o755),
    ("data/kaptan.desktop", "usr/share/applications/kaptan.desktop", 0o644),
    ("data/kaptan.svg", "usr/share/icons/hicolor/scalable/apps/kaptan.svg", 0o644),
    ("debian/kaptan.1", "usr/share/man/man1/kaptan.1.gz", 0o644),
    ("README.md", "usr/share/doc/kaptan/README.md", 0o644),
    ("LICENSE", "usr/share/licenses/kaptan/LICENSE", 0o644),
]


def pkgbuild_vars():
    """Let bash source the PKGBUILD and print each variable NUL-separated."""
    keys = ["pkgname", "pkgver", "pkgrel", "pkgdesc", "url", "license", "depends", "optdepends", "makedepends"]
    script = 'source "$1"; shift; for k; do declare -n v=$k; printf "%s\\0" "${v[@]}"; printf "\\1\\0"; unset -n v; done'
    raw = subprocess.run(["bash", "-c", script, "bash", os.path.join(HERE, "PKGBUILD"), *keys],
                         check=True, capture_output=True).stdout.decode()
    vals, cur = [], []
    for item in raw.split("\0")[:-1]:
        if item == "\1":
            vals.append(cur)
            cur = []
        else:
            cur.append(item)
    out = dict(zip(keys, vals))
    for k in ("pkgname", "pkgver", "pkgrel", "pkgdesc", "url"):
        out[k] = out[k][0]
    return out


def main(tree, outdir):
    v = pkgbuild_vars()
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))
    payload = {}
    for src, dst, mode in FILES:
        data = open(os.path.join(tree, src), "rb").read()
        if dst.endswith(".gz") and not src.endswith(".gz"):
            data = gzip.compress(data, mtime=epoch)  # makepkg compresses man pages
        payload[dst] = (data, mode)
    size = sum(len(d) for d, _ in payload.values())

    info = [f"# Generated by kaptan packaging/arch/mkpkg.py", f"pkgname = {v['pkgname']}",
            f"pkgbase = {v['pkgname']}", f"pkgver = {v['pkgver']}-{v['pkgrel']}",
            f"pkgdesc = {v['pkgdesc']}", f"url = {v['url']}", f"builddate = {epoch}",
            f"packager = {os.environ.get('PACKAGER', 'Unknown Packager')}", f"size = {size}",
            "arch = x86_64"]
    info += [f"license = {x}" for x in v["license"]]
    info += [f"depend = {x}" for x in v["depends"]]
    info += [f"optdepend = {x}" for x in v["optdepends"]]
    info += [f"makedepend = {x}" for x in v["makedepends"]]
    pkginfo = ("\n".join(info) + "\n").encode()

    # directories, parents first
    dirs = sorted({"/".join(p.split("/")[:i]) for p in payload for i in range(1, p.count("/") + 1)})

    def mtree_line(name, kind, mode, data=None):
        line = f"./{name} time={epoch}.0 mode={mode:o} type={kind}"
        if data is not None:
            line += f" size={len(data)} md5digest={hashlib.md5(data).hexdigest()}" \
                    f" sha256digest={hashlib.sha256(data).hexdigest()}"
        return line

    mt = ["#mtree", "/set type=file uid=0 gid=0 mode=644",
          mtree_line(".PKGINFO", "file", 0o644, pkginfo)]
    mt += [mtree_line(d, "dir", 0o755) for d in dirs]
    mt += [mtree_line(p, "file", m, d) for p, (d, m) in sorted(payload.items())]
    mtree = gzip.compress(("\n".join(mt) + "\n").encode(), mtime=epoch)

    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.GNU_FORMAT) as tar:
        def add(name, data=None, mode=0o644):
            ti = tarfile.TarInfo(name)
            ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = epoch, 0, 0, "root", "root"
            if data is None:
                ti.type, ti.mode = tarfile.DIRTYPE, 0o755
                tar.addfile(ti)
            else:
                ti.size, ti.mode = len(data), mode
                tar.addfile(ti, io.BytesIO(data))
        add(".PKGINFO", pkginfo)
        add(".MTREE", mtree)
        for d in dirs:
            add(d)
        for p, (d, m) in sorted(payload.items()):
            add(p, d, m)

    os.makedirs(outdir, exist_ok=True)
    out = os.path.join(outdir, f"{v['pkgname']}-{v['pkgver']}-{v['pkgrel']}-x86_64.pkg.tar.zst")
    subprocess.run(["zstd", "-q", "-19", "-T0", "-f", "-o", out], input=buf.getvalue(), check=True)
    print(out)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
